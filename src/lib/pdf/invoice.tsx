import type { CompanyProfile } from "@/lib/settings";
import type { InvoiceLine } from "@/lib/billing/terms";
import { formatMoneyPlain } from "@/lib/billing/terms";
import { GST_STATES, type TaxLine } from "@/lib/billing/gst";
import { DataTable, KeyValues, Paragraph, PdfDocument, Section, pdfDate } from "@/lib/pdf/kit";

export interface InvoiceDoc {
  number: string;
  issuedAt: Date;
  dueAt: Date | null;
  periodFrom: Date;
  periodTo: Date;
  currency: string;
  lines: InvoiceLine[];
  subtotal: number;
  taxMode: string | null;
  taxLines: TaxLine[];
  total: number;
  sac: string | null;
  status: string;
  voidReason: string | null;
  contractReference: string | null;
  supplier: { name: string; address: string; gstin: string | null; state: string | null; email?: string };
  recipient: { name: string; address: string; gstin: string; state: string | null; inIndia: boolean; email?: string; poNumber?: string };
  paymentDetails: string;
}

const stateLabel = (code: string | null) => (code ? `${GST_STATES[code] ?? "Unknown"} (${code})` : "—");

// A tax invoice with what the CGST rules ask for: supplier and recipient
// with GSTINs, a serial number unique for the financial year, the date,
// SAC, taxable value, each tax with its rate, the place of supply, and
// whether tax is payable on reverse charge.
export function InvoicePdf({ inv, company }: { inv: InvoiceDoc; company: CompanyProfile }) {
  const money = (minor: number) => formatMoneyPlain(minor, inv.currency);
  const gst = inv.taxMode === "intra" || inv.taxMode === "inter";
  return (
    <PdfDocument
      title={`${gst ? "Tax invoice" : "Invoice"} ${inv.number}${inv.status === "VOID" ? " (VOID)" : ""}`}
      subtitle={`Issued ${pdfDate(inv.issuedAt, false)}${inv.dueAt ? ` · due ${pdfDate(inv.dueAt, false)}` : ""}${inv.contractReference ? ` · contract ${inv.contractReference}` : ""}`}
      docLabel={`Invoice ${inv.number}`}
      company={company}
    >
      {inv.status === "VOID" && <Paragraph>This invoice was voided: {inv.voidReason}</Paragraph>}
      <Section title="From">
        <KeyValues items={[["Supplier", inv.supplier.name], ["Address", inv.supplier.address], ["GSTIN", inv.supplier.gstin], ["State", inv.supplier.state ? stateLabel(inv.supplier.state) : null]]} />
      </Section>
      <Section title="Bill to">
        <KeyValues items={[["Recipient", inv.recipient.name], ["Address", inv.recipient.address], ["GSTIN", inv.recipient.gstin || "Unregistered"], ["Place of supply", inv.recipient.inIndia ? stateLabel(inv.recipient.state) : "Outside India"], ["Purchase order", inv.recipient.poNumber]]} />
      </Section>
      <Section title="Services">
        <DataTable
          columns={[{ label: "Description", width: "52%" }, { label: "SAC", width: "10%" }, { label: "Quantity", width: "10%", align: "right" }, { label: "Rate", width: "14%", align: "right" }, { label: "Amount", width: "14%", align: "right" }]}
          rows={inv.lines.map((l) => [l.description, inv.sac ?? "", String(l.quantity), money(l.unitPrice), money(l.amount)])}
        />
      </Section>
      <Section title="Totals">
        <KeyValues
          items={[
            ["Taxable value", money(inv.subtotal)],
            ...inv.taxLines.map((t) => [t.label, money(t.amount)] as [string, string]),
            ["Total", money(inv.total)],
            ["Tax payable on reverse charge", "No"],
          ]}
        />
        {inv.taxMode === "export" && <Paragraph>Export of services: supply meant for export under a letter of undertaking, without payment of integrated tax.</Paragraph>}
        {inv.taxMode === "none" && <Paragraph muted>No GST charged.</Paragraph>}
      </Section>
      {inv.paymentDetails && (
        <Section title="Payment">
          <Paragraph>{inv.paymentDetails}</Paragraph>
        </Section>
      )}
      <Paragraph muted>For {inv.supplier.name}: authorised signatory. Generated by HELIOS; sign it, or issue it through your e-invoicing system where that applies to you.</Paragraph>
    </PdfDocument>
  );
}
